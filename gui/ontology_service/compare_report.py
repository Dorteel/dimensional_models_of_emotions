"""Exports of a domain comparison (ontology_service.compare): CSV table, Markdown and HTML summaries.

The summaries are built once as a list of blocks and rendered to Markdown or HTML, so both contain the same
content: model identifiers, dimensions (labels, ranges, definitions), dimension correspondence, shared and
unique emotions, the comparison table, missing-information warnings and provenance.

The HTML is self-contained (inline CSS, no external resources). It has a figures section marked with
FIGURES_MARKER; the browser replaces the marker with the two exported plot SVGs.
"""

from __future__ import annotations

import csv
import html
import io
import re

FIGURES_MARKER = "<!-- figures -->"


def _local(iri: str) -> str:
    return str(iri).rsplit("#", 1)[-1].rsplit("/", 1)[-1]


def _range_text(d) -> str:
    return d["range"] if d["rangeStated"] else d["rangeState"]


def table(c) -> tuple[list[str], list[list[str]]]:
    """The comparison table: one row per matched prototype pair, unique emotion or unclassified prototype."""
    pairs = [p for p in c["dimensions"]["pairs"] if p["compatible"]]
    header = (["status", "emotion class", "emotion class IRI", "A prototype", "A prototype IRI"]
              + [f"A {d['label']} [{_local(d['id'])}]" for d in c["a"]["dimensions"]]
              + ["B prototype", "B prototype IRI"]
              + [f"B {d['label']} [{_local(d['id'])}]" for d in c["b"]["dimensions"]]
              + [f"B − A {p['aLabel']} / {p['bLabel']}" for p in pairs]
              + (["Euclidean distance"] if c["dimensions"]["distance"] else []) + ["notes"])
    index = [i for i, p in enumerate(c["dimensions"]["pairs"]) if p["compatible"]]
    rows = []
    for r in c["rows"]:
        line = [r["status"], r["class"]["label"] if r["class"] else "", r["class"]["id"] if r["class"] else ""]
        notes = list(r["notes"])
        for side, dims in (("a", c["a"]["dimensions"]), ("b", c["b"]["dimensions"])):
            p = r[side]
            line += [p["label"], p["id"]] if p else ["", ""]
            for i, d in enumerate(dims):
                v = p["values"][i] if p else None
                line.append(v["raw"] if v and v["status"] == "ok" else "")
                key = f"{side.upper()} {d['label']}: {v['status']}" if v and v["status"] != "ok" else None
                if key and not any(n.startswith(key) for n in notes):
                    notes.append(key + (f" ({v['raw']})" if v["raw"] else ""))
        line += [r["differences"][i]["value"] or "" if r["differences"] else "" for i in index]
        if c["dimensions"]["distance"]:
            line.append(r["distance"] or "")
        line.append("; ".join(notes))
        rows.append(line)
    return header, rows


def to_csv(c) -> str:
    """CSV of the comparison table, preceded by '#' metadata lines (identifiers, dimensions, warnings, source)."""
    out = io.StringIO()
    p = c["provenance"]
    meta = [f"Comparison of domain models: A = {c['a']['label']}, B = {c['b']['label']}",
            f"A: {c['a']['id']}", f"B: {c['b']['id']}",
            f"source: {p['file']} sha256 {p['sha256']} ({p['parser']}; queries {', '.join(p['queries'])})"]
    for side in ("a", "b"):
        for d in c[side]["dimensions"]:
            meta.append(f"{side.upper()} dimension {d['label']}: {d['id']}; "
                        f"{'range ' + d['range'] if d['rangeStated'] else d['rangeState']}; "
                        f"definition {d['definitionState']}")
    meta.append(f"dimension correspondence: {c['dimensions']['equivalence']}")
    meta += [f"warning [{w['scope']}]: {w['text']}" for w in c["warnings"]]
    for line in meta:
        out.write("# " + line.replace("\n", " ") + "\r\n")
    writer = csv.writer(out)
    header, rows = table(c)
    writer.writerow(header)
    writer.writerows(rows)
    return out.getvalue()


# ------------------------------------------------------------------ summary document

def summary_blocks(c) -> list[tuple]:
    """Blocks: ("h", level, text) ("p", text) ("list", [text]) ("table", header, rows) ("figures",)."""
    a, b, dims, emo, prov = c["a"], c["b"], c["dimensions"], c["emotions"], c["provenance"]
    blocks = [("h", 1, f"Domain model comparison: {a['label']} vs {b['label']}"),
              ("p", "Generated by the Compare Domain Models tab from the populated ontology via SPARQL. "
                    "Nothing in this summary is inferred: missing information is reported as missing.")]
    blocks += [("h", 2, "Models"),
               ("table", ["", "A", "B"], [
                   ["label", a["label"], b["label"]],
                   ["IRI", a["id"], b["id"]],
                   ["model types", ", ".join(a["modelTypes"]) or "not stated", ", ".join(b["modelTypes"]) or "not stated"],
                   ["description", "; ".join(t["text"] for t in a["description"]) or "not stated",
                    "; ".join(t["text"] for t in b["description"]) or "not stated"],
                   ["dimensions", str(len(a["dimensions"])), str(len(b["dimensions"]))],
                   ["prototypes", str(a["prototypes"]), str(b["prototypes"])],
                   ["with complete coordinates", str(a["plotted"]), str(b["plotted"])],
                   ["emotion classes", str(a["emotionClasses"]), str(b["emotionClasses"])],
                   ["prototypes without emotion class", str(a["unclassified"]), str(b["unclassified"])]])]
    for side, d in (("A", a), ("B", b)):
        blocks.append(("h", 2, f"Dimensions of {side}: {d['label']}"))
        if d["dimensions"]:
            blocks.append(("table", ["dimension", "IRI", "range", "circular", "definition", "definition source"], [
                [x["label"], x["id"], _range_text(x), ", ".join(x["circular"]) or "not stated",
                 "; ".join(t["text"] + (" (placeholder)" if t["placeholder"] else "") for t in x["definitions"]) or "not stated",
                 "; ".join(s for t in x["definitions"] for s in t["sources"]) or "not stated"] for x in d["dimensions"]]))
        else:
            blocks.append(("p", "No quality dimensions."))
    blocks.append(("h", 2, "Dimension correspondence"))
    blocks.append(("p", {"none": "None established in the ontology: structural comparison only, without numerical "
                                 "differences or distances.",
                         "partial": "Partial: only some dimensions have a stated counterpart; no distance is computed.",
                         "full": "Full: every dimension of A has exactly one stated counterpart in B and vice versa."}
                   [dims["equivalence"]]))
    if dims["pairs"]:
        blocks.append(("table", ["A dimension", "B dimension", "basis", "differences computed", "reason"], [
            [p["aLabel"], p["bLabel"], p["basis"], "yes" if p["compatible"] else "no", "; ".join(p["reasons"])]
            for p in dims["pairs"]]))
    blocks.append(("h", 2, "Figures"))
    blocks.append(("figures",))
    blocks.append(("h", 2, "Emotions"))
    blocks.append(("p", f"{len(emo['shared'])} shared emotion classes, {len(emo['onlyA'])} only in A, "
                        f"{len(emo['onlyB'])} only in B (matched by emotion class IRI only)."))
    blocks.append(("list", [f"Shared: {', '.join(e['label'] for e in emo['shared']) or 'none'}",
                            f"Only in A: {', '.join(e['label'] for e in emo['onlyA']) or 'none'}",
                            f"Only in B: {', '.join(e['label'] for e in emo['onlyB']) or 'none'}"]))
    blocks.append(("h", 2, "Comparison table"))
    header, rows = table(c)
    blocks.append(("table", header, rows) if rows else ("p", "No prototypes in either domain."))
    blocks.append(("h", 2, "Missing information and warnings"))
    blocks.append(("list", [f"[{w['scope']}] {w['text']}" for w in c["warnings"]] or ["None."]))
    blocks.append(("h", 2, "Provenance"))
    blocks.append(("list", [f"Ontology file: {prov['file']} (sha256 {prov['sha256']}, {prov['triples']} triples, "
                            f"{prov['parser']})",
                            f"Base IRI: {prov['base']}",
                            f"SPARQL queries: {', '.join(prov['queries'])}",
                            "Sources cited by A's definitions: " + (", ".join(s["label"] for s in prov["sourcesA"]) or "none"),
                            "Sources cited by B's definitions: " + (", ".join(s["label"] for s in prov["sourcesB"]) or "none"),
                            *prov["rules"]]))
    return blocks


def _md(text) -> str:
    return str(text).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def to_markdown(c) -> str:
    lines = []
    for block in summary_blocks(c):
        kind = block[0]
        if kind == "h":
            lines += ["#" * block[1] + " " + _md(block[2]), ""]
        elif kind == "p":
            lines += [_md(block[1]), ""]
        elif kind == "list":
            lines += [f"- {_md(x)}" for x in block[1]] + [""]
        elif kind == "table":
            header, rows = block[1], block[2]
            lines.append("| " + " | ".join(_md(h) for h in header) + " |")
            lines.append("|" + "---|" * len(header))
            lines += ["| " + " | ".join(_md(x) for x in r) + " |" for r in rows]
            lines.append("")
        elif kind == "figures":
            lines += ["Figures are exported separately (SVG/PNG) or embedded in the HTML summary.", ""]
    return "\n".join(lines)


STYLE = """
body { font: 14px/1.45 system-ui, sans-serif; color: #1d2330; background: #fff; margin: 24px auto; max-width: 1200px; padding: 0 16px; }
h1 { font-size: 22px; } h2 { font-size: 17px; margin-top: 28px; border-bottom: 1px solid #dde1e8; padding-bottom: 3px; }
table { border-collapse: collapse; font-size: 12px; margin: 8px 0; display: block; overflow-x: auto; }
th, td { border: 1px solid #dde1e8; padding: 3px 7px; text-align: left; vertical-align: top; }
th { background: #f6f7f9; }
.figures { display: flex; flex-wrap: wrap; gap: 16px; }
.figures figure { margin: 0; flex: 1 1 480px; } .figures svg { width: 100%; height: auto; border: 1px solid #dde1e8; }
"""


def to_html(c) -> str:
    e = html.escape
    out = ["<!doctype html>", '<html lang="en">', "<head>", '<meta charset="utf-8">',
           f"<title>{e(c['a']['label'])} vs {e(c['b']['label'])}: domain model comparison</title>",
           f"<style>{STYLE}</style>", "</head>", "<body>"]
    for block in summary_blocks(c):
        kind = block[0]
        if kind == "h":
            out.append(f"<h{block[1]}>{e(block[2])}</h{block[1]}>")
        elif kind == "p":
            out.append(f"<p>{e(block[1])}</p>")
        elif kind == "list":
            out.append("<ul>" + "".join(f"<li>{e(x)}</li>" for x in block[1]) + "</ul>")
        elif kind == "table":
            out.append("<table><thead><tr>" + "".join(f"<th>{e(h)}</th>" for h in block[1]) + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{e(x)}</td>" for x in r) + "</tr>" for r in block[2])
                       + "</tbody></table>")
        elif kind == "figures":
            out.append(f'<div class="figures">{FIGURES_MARKER}</div>')
    out += ["</body>", "</html>", ""]
    return "\n".join(out)


def file_stem(c) -> str:
    safe = lambda name: re.sub(r"[^A-Za-z0-9_-]+", "_", name)  # noqa: E731  (names may be prefixed, e.g. ecs:x)
    return f"compare_{safe(c['a']['name'])}_vs_{safe(c['b']['name'])}"
